"""### 2.3 Outliers (método IQR)

Se **detectan y se documentan**, pero **no se eliminan**. Motivos para justificar en el reporte (editar si cambian de decisión):

- Eliminar las filas con un outlier en *cualquier* variable numérica quita muchos estudiantes. Revisen la columna "Porcentaje" de la tabla.
- Son datos académicos: valores como pocas unidades curriculares aprobadas o edades altas son reales y pueden ser justamente señal de deserción.
- Si se eliminara algo, debería hacerse **solo en el conjunto de entrenamiento**, nunca en el de prueba.
"""

def resumen_outliers_iqr(data, variables):
    filas = []
    for v in variables:
        q1, q3 = data[v].quantile(0.25), data[v].quantile(0.75)
        iqr = q3 - q1
        inf, sup = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        n = int(((data[v] < inf) | (data[v] > sup)).sum())
        filas.append({"Variable": v, "Límite inferior": round(inf, 2), "Límite superior": round(sup, 2),
                      "Outliers": n, "Porcentaje": round(n / len(data) * 100, 2)})
    return pd.DataFrame(filas).sort_values("Outliers", ascending=False).reset_index(drop=True)

